package peek_test

import (
	"bytes"
	"fmt"
	"runtime"
	"testing"

	"github.com/git-pkgs/peek"
)

func benchmarkInput(header string) []byte {
	data := bytes.Repeat([]byte("// ordinary source line\n"), 64)
	copy(data, header)
	return data[:1024]
}

func BenchmarkInspect(b *testing.B) {
	for _, tc := range []struct{ name, header string }{
		{"plain", ""},
		{"script", "#!/usr/bin/env -S python3 -u\n# coding: utf-8\n# SPDX-License-Identifier: MIT\n"},
		{"generated", "// Code generated by wire. DO NOT EDIT.\n// source: input.proto\n// https://example.org/schema\n"},
		{"xml", "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n"},
	} {
		b.Run(tc.name, func(b *testing.B) {
			input := peek.Input{Bytes: benchmarkInput(tc.header)}
			b.ReportAllocs()
			b.SetBytes(int64(len(input.Bytes)))
			for b.Loop() {
				_ = peek.Inspect(input)
			}
		})
	}
}

func BenchmarkReuse(b *testing.B) {
	input := peek.Input{Bytes: benchmarkInput("#!/bin/sh\n# SPDX-License-Identifier: MIT\n")}
	result := peek.Inspect(input)
	b.ReportAllocs()
	b.SetBytes(int64(len(input.Bytes)))
	for b.Loop() {
		peek.InspectInto(&result, input)
	}
}

func BenchmarkParallel(b *testing.B) {
	input := peek.Input{Bytes: benchmarkInput("#!/bin/sh\n# SPDX-License-Identifier: MIT\n")}
	b.ReportAllocs()
	b.SetBytes(int64(len(input.Bytes)))
	b.RunParallel(func(pb *testing.PB) {
		var result peek.Result
		for pb.Next() {
			peek.InspectInto(&result, input)
		}
	})
}

func BenchmarkBatch(b *testing.B) {
	batch := benchmarkBatch()
	result := peek.Inspect(peek.Input{Bytes: batch[:1024]})
	b.ReportAllocs()
	b.SetBytes(int64(len(batch)))
	b.ResetTimer()
	for range b.N {
		for i := range len(batch) / 1024 {
			peek.InspectInto(&result, peek.Input{Bytes: batch[i*1024 : (i+1)*1024]})
		}
	}
}

func BenchmarkBatchMemory(b *testing.B) {
	batch := benchmarkBatch()
	result := peek.Inspect(peek.Input{Bytes: batch[:1024]})
	var before, after runtime.MemStats
	runtime.GC()
	runtime.ReadMemStats(&before)
	b.ResetTimer()
	for i := range b.N {
		start := (i % (len(batch) / 1024)) * 1024
		peek.InspectInto(&result, peek.Input{Bytes: batch[start : start+1024]})
	}
	b.StopTimer()
	runtime.ReadMemStats(&after)
	b.ReportMetric(float64(after.TotalAlloc-before.TotalAlloc)/float64(b.N), "batch-B/item")
	b.ReportMetric(float64(after.HeapAlloc), "heap-B")
	runtime.KeepAlive(result)
	runtime.KeepAlive(batch)
}

func benchmarkBatch() []byte {
	const count = 4096
	batch := make([]byte, count*1024)
	headers := [...]string{"#!/bin/sh\n# SPDX-License-Identifier: MIT\n", "// Code generated by wire. DO NOT EDIT.\n", "<?xml encoding='UTF-8'?>\n", ""}
	for i := range count {
		copy(batch[i*1024:], benchmarkInput(headers[i%len(headers)]))
	}
	return batch
}

func BenchmarkAdversarial(b *testing.B) {
	for _, size := range []int{1024, peek.MaxBytes} {
		for _, pattern := range []string{"x", "https://x \n", "# SPDX-License-Identifier: x\n"} {
			b.Run(fmt.Sprintf("%d/%s", size, pattern), func(b *testing.B) {
				data := bytes.Repeat([]byte(pattern), size/len(pattern)+1)[:size]
				input := peek.Input{Bytes: data}
				result := peek.Inspect(input)
				b.ReportAllocs()
				b.SetBytes(int64(size))
				for b.Loop() {
					peek.InspectInto(&result, input)
				}
			})
		}
	}
}
